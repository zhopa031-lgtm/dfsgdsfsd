# -*- coding: utf-8 -*-
"""Генератор персональных сообщений для заказчика.

Тексты заполняются данными конкретного лида (название, город, ниша) и не
содержат выдуманных фактов — только честное наблюдение «сайта нет» и оффер.
Для каждого лида 3 варианта: тёплый, короткий деловой, через выгоду.
"""
from __future__ import annotations

from .niches import NICHE_BENEFITS, NICHE_LABELS, NICHE_LABELS_GEN

TEMPLATES = [
    # 1 — тёплый и наблюдательный
    (
        "Здравствуйте! Пишу по поводу «{name}» ({city}). "
        "У вас пока нет сайта, а клиенты {niche_gen} почти всё ищут в Яндексе и на картах — "
        "туда попадают в первую очередь те, у кого есть сайт с описанием и записью.\n\n"
        "Я делаю такие сайты под ключ: {benefit}, адаптация под телефон, заявки приходят "
        "в WhatsApp или Telegram. Могу сначала собрать демо-страницу по вашему бизнесу — "
        "посмотрите до оплаты.\n\n"
        "Удобно обсудить здесь или по телефону?"
    ),
    # 2 — короткий и деловой
    (
        "Добрый день! Я делаю сайты для {niche_gen} в {city}.\n\n"
        "У «{name}» сайта не нашлось — значит, в поиске Яндекса клиентов видят "
        "только конкуренты. Могу за 5-7 дней сделать сайт: {benefit}. "
        "Фиксированная цена, правки до результата.\n\n"
        "Показать примеры и посчитать под вас? Пишите прямо сюда 👋"
    ),
    # 3 — через выгоду
    (
        "Здравствуйте! Вопрос по «{name}»: сколько заявок вам сейчас приносит сайт?\n\n"
        "Если ноль — его просто нет, и это решаемо. Собираю сайты для {niche_gen}: "
        "{benefit}. Делаю быстро, показываю демо до оплаты, веду после запуска.\n\n"
        "Могу скинуть, как это будет выглядеть у вас — написать сюда или на телефон?"
    ),
]

WEB_REPLY_TEMPLATE = (
    "Здравствуйте! Увидел(а) ваш запрос про сайт. Делаю сайты под ключ: лендинги, "
    "каталоги, онлайн-запись и приём заявок в Telegram/WhatsApp. "
    "Расскажите пару слов о задаче — бесплатно оценю сроки и цену, "
    "сразу скину похожие работы из портфолио."
)


def build_texts(lead: dict, settings) -> list[str]:
    """3 персональных варианта текста для лида."""
    name = lead.get("name") or "ваш бизнес"
    city = lead.get("city") or settings.city_main
    niche = lead.get("niche") or "services"
    niche_gen = NICHE_LABELS_GEN.get(niche, "сервисных бизнесов")
    benefit = NICHE_BENEFITS.get(niche, "каталог услуг и запись онлайн")

    texts = [tpl.format(name=name, city=city, niche_gen=niche_gen, benefit=benefit)
             for tpl in TEMPLATES]
    signature = (settings.get("sender_name") or "").strip()
    if signature:
        texts = [t + f"\n\n— {signature}" for t in texts]
    return texts


def web_reply_text() -> str:
    return WEB_REPLY_TEMPLATE


def niche_label(niche: str) -> str:
    return NICHE_LABELS.get(niche, niche)
